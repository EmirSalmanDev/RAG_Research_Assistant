// The paper page: analysis, code, Hugging Face artifacts and the three related-paper tabs.
//
// WHAT THIS PROVES, AND WHAT IT DOES NOT. The API behind /api is the mock in
// e2e/mock-api.ts (one invented paper), reached through the real Next.js /api rewrite. So
// this proves the page renders every section and the tabs work with the keyboard; it does
// not prove anything about the real enrichment or analyses (that is a separate run against
// the real API).
//
// CONTAINMENT. Same as the chat test: every non-local request is aborted and recorded,
// and external links (GitHub, Hugging Face, arXiv) are checked by their href only, never
// opened.
import { expect, test } from "@playwright/test";

import { isAllowedUrl } from "./containment.ts";

test("a paper page shows its analysis, code, models, datasets and three related tabs", async ({
  page,
  context,
}) => {
  const blocked: string[] = [];
  await context.route("**/*", (route) => {
    const url = route.request().url();
    if (isAllowedUrl(url)) return route.continue();
    blocked.push(url);
    return route.abort("blockedbyclient");
  });
  const pageErrors: string[] = [];
  page.on("pageerror", (error) => pageErrors.push(String(error)));

  await page.goto("/paper/2609.00001", { waitUntil: "domcontentloaded" });
  await expect(
    page.getByRole("heading", { name: "An Invented Paper About Adapters" }),
  ).toBeVisible();

  await test.step("the analysis", async () => {
    await expect(page.getByRole("heading", { name: "Analysis" })).toBeVisible();
    await expect(
      page.getByText("Invented TL;DR: small adapters match full fine-tuning."),
    ).toBeVisible();
    await expect(page.getByText("An invented evaluation.")).toBeVisible();
    await expect(
      page.getByText(/Generated by gpt-4o-mini \(analyze_v1\)/),
    ).toBeVisible();
  });

  await test.step("code, models and datasets with checked links", async () => {
    const repo = page.getByRole("link", { name: "invented-org/adapters" });
    await expect(repo).toHaveAttribute(
      "href",
      "https://github.com/invented-org/adapters",
    );
    await expect(page.getByText("(1.5k stars, Apache-2.0,")).toBeVisible();
    await expect(page.getByText("Models on Hugging Face (11)")).toBeVisible();
    const models = page.getByRole("link", {
      name: /^invented-org\/adapter-model-/,
    });
    await expect(models).toHaveCount(8); // the first eight, most downloaded first
    await expect(models.first()).toHaveText("invented-org/adapter-model-1");
    await page.getByRole("button", { name: "Show all 11" }).click();
    await expect(models).toHaveCount(11);
    await expect(
      page.getByRole("link", { name: "invented-org/adapter-data" }),
    ).toHaveAttribute(
      "href",
      "https://huggingface.co/datasets/invented-org/adapter-data",
    );
    await expect(
      page.getByText("None linked to this paper on Hugging Face."),
    ).toBeVisible(); // Spaces
  });

  await test.step("three related-paper tabs, keyboard included", async () => {
    const tabs = page.getByRole("tab");
    await expect(tabs).toHaveText(["Similar (1)", "Cites (1)", "Cited by (1)"]);
    const panel = page.getByRole("tabpanel");
    await expect(
      panel.getByRole("link", { name: "A Similar Invented Paper" }),
    ).toHaveAttribute("href", "/paper/2609.00002");

    await tabs.first().focus();
    await page.keyboard.press("ArrowRight");
    await expect(page.getByRole("tab", { name: "Cites (1)" })).toHaveAttribute(
      "aria-selected",
      "true",
    );
    await expect(page.getByRole("tab", { name: "Cites (1)" })).toBeFocused();
    await expect(
      panel.getByRole("link", { name: "arXiv 1706.00000" }),
    ).toHaveAttribute("href", "https://arxiv.org/abs/1706.00000");
    await expect(panel.getByText("(not in the local index)")).toBeVisible();

    await page.keyboard.press("End");
    await expect(
      panel.getByRole("link", { name: "A Citing Invented Paper" }),
    ).toHaveAttribute("href", "/paper/2609.00003");
  });

  expect(pageErrors).toEqual([]);
  expect(blocked).toEqual([]); // nothing on this page tried to leave the machine
});
