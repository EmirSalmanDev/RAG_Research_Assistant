import type { PaperDetailsOut } from "@/lib/api/queries";
import { formatDate } from "@/lib/format";

// The generated analysis of a paper (GET /papers/{id}/details). Analyses are made in the
// background by the Batch API for full-text papers, so a page can show one of three
// states: available, queued (results within 24 hours) or none yet.
export function AnalysisSection({
  details,
  fulltextIndexed,
}: {
  details: PaperDetailsOut;
  fulltextIndexed: boolean;
}) {
  const a = details.analysis;
  return (
    <section aria-labelledby="analysis-heading" className="space-y-4">
      <h2 id="analysis-heading" className="text-lg font-semibold">
        Analysis
      </h2>
      {details.analysis_status === "queued" && (
        <p className="text-muted-foreground">
          An analysis of this paper is queued. Results arrive within 24 hours.
        </p>
      )}
      {details.analysis_status === "none" && (
        <p className="text-muted-foreground">
          {fulltextIndexed
            ? "This paper has not been analysed yet."
            : "Analyses are made for papers whose full text is indexed; this paper has only its abstract."}
        </p>
      )}
      {a && (
        <>
          <dl className="space-y-4">
            {a.tldr && <Field label="TL;DR" text={a.tldr} />}
            {a.contributions.length > 0 && (
              <div className="space-y-1">
                <dt className="text-sm font-medium text-muted-foreground">
                  Contributions
                </dt>
                <dd>
                  <ul className="list-disc space-y-1 pl-5 leading-7">
                    {a.contributions.map((item, i) => (
                      <li key={i}>{item}</li>
                    ))}
                  </ul>
                </dd>
              </div>
            )}
            {a.method && <Field label="Method" text={a.method} />}
            {a.results && <Field label="Results" text={a.results} />}
            {a.limitations && (
              <Field label="Limitations" text={a.limitations} />
            )}
          </dl>
          <p className="text-xs text-muted-foreground">
            Generated by {a.model}
            {a.prompt_version ? ` (${a.prompt_version})` : ""} from the paper
            text on {formatDate(a.created_at)}. It can contain mistakes: check
            it against the passages below.
          </p>
        </>
      )}
    </section>
  );
}

function Field({ label, text }: { label: string; text: string }) {
  return (
    <div className="space-y-1">
      <dt className="text-sm font-medium text-muted-foreground">{label}</dt>
      <dd className="whitespace-pre-wrap leading-7">{text}</dd>
    </div>
  );
}
